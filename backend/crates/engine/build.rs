//! Registers every `defaults/templates/*.json` as a shipped reference architecture: a template is a file, not a line to remember to add.

use std::{env, fs, path::PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let dir = manifest.join("defaults/templates");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut ids: Vec<String> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .filter_map(|entry| {
            let path = entry.ok()?.path();
            (path.extension()? == "json").then(|| path.file_stem()?.to_str().map(str::to_string)).flatten()
        })
        .collect();
    ids.sort();
    let mut code = String::from("/// The reference architectures that ship with the binary (generated by build.rs from `defaults/templates`).\npub const TEMPLATES_JSON: &[(&str, &str)] = &[\n");
    for id in &ids {
        code.push_str(&format!("    ({id:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/defaults/templates/{id}.json\"))),\n"));
    }
    code.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("templates.rs"), code).expect("write templates.rs");
}
